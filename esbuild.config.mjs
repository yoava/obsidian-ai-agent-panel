import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import { readFileSync } from "node:fs";

// esbuild matches an external against the exact specifier, so a builtin has to
// be listed under both spellings. A handful of entries ("node:sqlite", …) are
// only ever spelled with the prefix, so don't prefix them twice.
const nodeBuiltins = builtinModules.flatMap((name) =>
	name.startsWith("node:") ? [name] : [name, `node:${name}`]
);

// The bundled fonts' full license texts and copyright notices ship in main.js
// (ADR-007 legal row). A "*/" inside a license text would close the comment.
const bundledLicenses = [
	["Geist", "@fontsource-variable/geist"],
	["Geist Mono", "@fontsource-variable/geist-mono"],
]
	.map(([name, pkg]) => {
		const text = readFileSync(`node_modules/${pkg}/LICENSE`, "utf8").trim().replaceAll("*/", "* /");
		return `---- ${name} (${pkg}) ----\n\n${text}`;
	})
	.join("\n\n");

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
If you want to view the source, visit the plugin's GitHub repository.

Bundled font data, unmodified; each font is licensed as follows.

${bundledLicenses}
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...nodeBuiltins,
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	loader: { ".woff2": "dataurl" },
	outfile: "main.js",
	minify: false,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
